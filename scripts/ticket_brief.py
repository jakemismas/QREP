"""Write one self-contained brief per sprint ticket for the worker that builds it.

A worker read a median 133K tokens before its first code edit, mostly slices
of a 392 KB plan and long issue threads (#278). This gathers what one ticket
needs into one file of a few KB, and the worker reads that instead
(docs/sprint-5/RESET.md section 3):

- the issue body;
- the comments that carry criteria ("- [ ]"), the reset's decisions (#278),
  and the latest HANDOFF;
- the ticket's plan section;
- each MATH.md and PATTERN-SPEC.md entry the text cites by id.

Usage:
    python scripts/ticket_brief.py C3b [--issue 101] [--out .claude/sprint/briefs]
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAN = ROOT / "docs" / "sprint-5" / "qrep-sprint-5-plan.md"
MATH = ROOT / "docs" / "sprint-5" / "MATH.md"
PATTERN_SPEC = ROOT / "docs" / "sprint-5" / "PATTERN-SPEC.md"
DEFAULT_OUT = ROOT / ".claude" / "sprint" / "briefs"
CHATTER = ("Launched", "PLAN", "PROGRESS", "HANDOFF", "MEASUREMENT", "Close-out",
           "IMPLEMENTATION NOTES", "Relaunch", "Orchestrator rotation")
COMMENT_CAP = 6000
ENTRY_CAP = 2500
ENTRIES_CAP = 16000
MATH_ID = r"F\d{1,2}|V-[A-Z]+-\d+|D-\d{2}|Q\d{1,2}"
SPEC_ID = r"PS-\d{2}|M-\d{2}|L-\d{2}|C-\d{2}|X-\d{2}|GAP-\d{2}"
CITED = re.compile(rf"\b({MATH_ID}|{SPEC_ID})\b")
IS_MATH = re.compile(rf"^(?:{MATH_ID})$")


def plan_section(plan: str, ticket: str) -> str | None:
    m = re.search(rf"^#### {re.escape(ticket)}:.*?(?=^#{{2,4}} |\Z)", plan, re.M | re.S)
    return m.group(0).rstrip() if m else None


def _kind(comment: dict) -> str:
    return comment["body"].lstrip("*# ")


def select_comments(comments: list[dict]) -> list[dict]:
    """Keep every comment except routine run chatter, plus the latest resume note.

    Carried criteria, rulings on BLOCKED questions, folded criteria, Jake's
    decisions and APPROACH FAILED notes bind the ticket whatever their wording,
    so the rule drops only the bulky notes a run leaves behind. The resume
    note is the latest HANDOFF, else PROGRESS, else PLAN: a ticket stopped
    mid-build may never have written a HANDOFF.
    """
    latest = None
    for kind in ("HANDOFF", "PROGRESS", "PLAN"):
        notes = [c for c in comments if _kind(c).startswith(kind)]
        if notes:
            latest = notes[-1]
            break
    return [c for c in comments if c is latest or not _kind(c).startswith(CHATTER)]


def folded_tickets(comments: list[dict]) -> list[str]:
    """Ticket ids folded into this one ("### From #125: A4d: ...")."""
    found = re.findall(r"^### From #\d+: ([A-E]\d{1,2}[a-z]?):", "\n".join(c["body"] for c in comments), re.M)
    return list(dict.fromkeys(found))


def cited_ids(text: str) -> list[str]:
    return list(dict.fromkeys(CITED.findall(text)))


def _clip(text: str, source: str) -> str:
    return text if len(text) <= ENTRY_CAP else text[:ENTRY_CAP] + f"\n[cut; read the rest in {source}]"


def definition(doc: str, ident: str, source: str) -> str | None:
    lines = doc.splitlines()
    heading = re.compile(rf"^(#{{2,5}})\s+{re.escape(ident)}\b")
    row = re.compile(rf"^\|\s*{re.escape(ident)}\s*\|")
    bullet = re.compile(rf"^\s*[-*]\s+(\*\*)?{re.escape(ident)}\b")
    for i, line in enumerate(lines):
        h = heading.match(line)
        if h:
            out = [line]
            for nxt in lines[i + 1:]:
                deeper = re.match(r"^(#{1,6})\s", nxt)
                if deeper and len(deeper.group(1)) <= len(h.group(1)):
                    break
                out.append(nxt)
            return _clip("\n".join(out).rstrip(), source)
        if row.match(line):
            return line
        if bullet.match(line):
            out = [line]
            for nxt in lines[i + 1:]:
                if not nxt.strip() or re.match(r"^\s*[-*]\s", nxt) or nxt.startswith("#"):
                    break
                out.append(nxt)
            return _clip("\n".join(out), source)
    return None


def build_brief(ticket: str, issue: dict, plan: str, math: str, spec: str) -> str:
    section = plan_section(plan, ticket)
    comments = select_comments(issue.get("comments", []))
    parts = [
        f"# Brief for {ticket} (#{issue['number']}): {issue['title']}",
        "Generated by scripts/ticket_brief.py. Read this, docs/sprint-5/RESET.md sections 3, "
        "4 and 6, and the code you change. Read nothing else of the plan.",
        "## Issue body",
        issue["body"].strip(),
    ]
    if comments:
        parts.append("## Criteria, rulings, decisions and the latest resume note")
        for c in comments:
            body = c["body"].strip()
            if len(body) > COMMENT_CAP:
                body = body[:COMMENT_CAP] + "\n[cut; read the rest on the issue]"
            parts.append(f"### Comment of {c.get('createdAt', '')[:16]}\n\n{body}")
    parts.append("## Plan section")
    parts.append(section or f"No `#### {ticket}:` section in the plan; the issue is the contract.")
    for folded in folded_tickets(comments):
        extra = plan_section(plan, folded)
        if extra:
            parts.append(
                f"## Plan section of {folded}, folded into this ticket\n\n"
                f"Context only: just the {folded} criteria copied in the Folded in comment "
                f"above apply.\n\n{extra}"
            )
    text = "\n\n".join(parts)
    entries, missing, used = [], [], 0
    for ident in cited_ids(text):
        source, doc = ("MATH.md", math) if IS_MATH.match(ident) else ("PATTERN-SPEC.md", spec)
        found = definition(doc, ident, source)
        if found is None or used + len(found) > ENTRIES_CAP:
            missing.append(f"{ident} ({source})")
            continue
        entries.append(found)
        used += len(found)
    if entries:
        parts.append("## Cited entries")
        parts.extend(entries)
    if missing:
        parts.append("Cited but not included (look up by id): " + ", ".join(missing))
    return "\n\n".join(parts) + "\n"


def find_issue(ticket: str) -> int:
    raw = subprocess.run(
        ["gh", "issue", "list", "--state", "all", "--limit", "300", "--search",
         f"{ticket} in:title", "--json", "number,title"],
        check=True, capture_output=True, text=True, encoding="utf-8",
    ).stdout
    hits = [i["number"] for i in json.loads(raw) if i["title"].startswith(f"{ticket}:")]
    if len(hits) != 1:
        raise SystemExit(f"expected one issue titled '{ticket}: ...', found {hits}; pass --issue")
    return hits[0]


def fetch_issue(number: int) -> dict:
    raw = subprocess.run(
        ["gh", "issue", "view", str(number), "--json", "number,title,body,comments"],
        check=True, capture_output=True, text=True, encoding="utf-8",
    ).stdout
    return json.loads(raw)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("ticket", help="ticket id, such as C3b")
    ap.add_argument("--issue", type=int)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    issue = fetch_issue(args.issue or find_issue(args.ticket))
    read = lambda p: p.read_text(encoding="utf-8")  # noqa: E731
    brief = build_brief(args.ticket, issue, read(PLAN), read(MATH), read(PATTERN_SPEC))
    args.out.mkdir(parents=True, exist_ok=True)
    path = args.out / f"{args.ticket}.md"
    path.write_text(brief, encoding="utf-8", newline="\n")
    print(f"{path} {len(brief.encode('utf-8')):,} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
